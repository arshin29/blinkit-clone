export function getTrendingProducts(apiProducts?: Product[]): Product[] {
  if (apiProducts && apiProducts.length > 0) {
    const trendingKeywords = [
      'amul taaza',
      'banana',
      'coca-cola',
      'magic masala',
      'maggi 2-minute',
      'cadbury dairy milk silk',
      'parle-g',
      'tata tea gold',
      'aashirvaad',
      'fortune sunlite',
      'tomato ketchup',
      'dettol antiseptic'
    ];
    const picked: Product[] = [];
    const usedIds = new Set<string>();

    for (const kw of trendingKeywords) {
      const match = apiProducts.find(
        (p) => !usedIds.has(p.id) && p.name.toLowerCase().includes(kw)
      );
      if (match) {
        picked.push({
          ...match,
          deliveryTime: match.deliveryTime || '27 MINS',
        });
        usedIds.add(match.id);
      }
    }

    if (picked.length >= 6) {
      return picked;
    }
  }

  const trendingMap = new Map(STATIC_PRODUCTS.map((p) => [p.id, p]));
  return TRENDING_PRODUCT_IDS.map((id) => trendingMap.get(id)).filter(
    (p): p is Product => p !== undefined
  );
}

