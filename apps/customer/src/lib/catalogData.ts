// Mapping to bridge API category slugs with static catalog
const CATEGORY_ALIAS_MAP: Record<string, string> = {
  'dairy-breakfast': 'dairy-bread-eggs',
  'cold-drinks-beverages': 'cold-drinks-juices',
  'instant-frozen-food': 'breakfast-instant-food',
};

export function normalizeCategorySlug(slugOrId: string): string {
  if (!slugOrId) return '';
  const clean = slugOrId.toLowerCase().trim();
  return CATEGORY_ALIAS_MAP[clean] || clean;
}

export function findCategoryBySlugOrId(slugOrId: string, apiCategories?: Category[]): CategoryWithSeo | undefined {
  if (!slugOrId) return undefined;
  const normalized = normalizeCategorySlug(slugOrId);

  // 1. Look in static categories
  const found = STATIC_CATEGORIES.find(
    (c) =>
      c.id.toLowerCase() === normalized ||
      c.slug.toLowerCase() === normalized ||
      c.name.toLowerCase() === normalized ||
      c.id.toLowerCase() === slugOrId.toLowerCase()
  );
  if (found) return found;

  // 2. Look in API categories
  if (apiCategories && apiCategories.length > 0) {
    const apiFound = apiCategories.find(
      (c) =>
        c.id === slugOrId ||
        c.slug.toLowerCase() === normalized ||
        normalizeCategorySlug(c.slug) === normalized
    );
    if (apiFound) {
      const staticMatch = STATIC_CATEGORIES.find(
        (sc) => sc.slug === normalizeCategorySlug(apiFound.slug)
      );
      return {
        ...apiFound,
        seoTitle: staticMatch?.seoTitle || `${apiFound.name} Online`,
        seoDescription:
          staticMatch?.seoDescription ||
          `Order fresh ${apiFound.name} delivered to your doorstep in 10-27 minutes at the lowest online prices from Blinkit.`,
      };
    }
  }

  return undefined;
}

export function getAllMergedProducts(apiProducts: Product[] = []): Product[] {
  const combined: Product[] = [];
  const seenNames = new Set<string>();

  for (const apiProd of apiProducts) {
    combined.push({
      ...apiProd,
      deliveryTime: apiProd.deliveryTime || '27 MINS',
    });
    seenNames.add(apiProd.name.toLowerCase().trim());
  }

  for (const staticProd of STATIC_PRODUCTS) {
    if (!seenNames.has(staticProd.name.toLowerCase().trim())) {
      combined.push(staticProd);
      seenNames.add(staticProd.name.toLowerCase().trim());
    }
  }

  return combined;
}

export function getProductsForCategory(
  categorySlugOrId: string,
  apiProducts: Product[] = []
): { products: Product[]; category?: CategoryWithSeo } {
  const category = findCategoryBySlugOrId(categorySlugOrId);
  const normalizedCatSlug = normalizeCategorySlug(categorySlugOrId);

  // Filter static products belonging to this category
  const matchingStatic = STATIC_PRODUCTS.filter((p) => {
    return (
      p.categoryId === normalizedCatSlug ||
      p.categoryId === categorySlugOrId ||
      (category && p.categoryId === category.id)
    );
  });

  // Filter API products if any
  const matchingApi = apiProducts.filter((p) => {
    const pCatSlug = p.category?.slug ? normalizeCategorySlug(p.category.slug) : '';
    const pCatId = p.categoryId || p.category?.id;
    return (
      pCatId === categorySlugOrId ||
      (category && pCatId === category.id) ||
      (pCatSlug && pCatSlug === normalizedCatSlug) ||
      (p.categoryId && normalizeCategorySlug(p.categoryId) === normalizedCatSlug)
    );
  });

  // Combine: prioritize API products so real database IDs are used for cart/checkout
  const combined: Product[] = [];
  const seenNames = new Set<string>();

  for (const apiProd of matchingApi) {
    combined.push({
      ...apiProd,
      deliveryTime: apiProd.deliveryTime || '27 MINS',
    });
    seenNames.add(apiProd.name.toLowerCase().trim());
  }

  for (const staticProd of matchingStatic) {
    if (!seenNames.has(staticProd.name.toLowerCase().trim())) {
      combined.push(staticProd);
      seenNames.add(staticProd.name.toLowerCase().trim());
    }
  }

  return {
    products: combined,
    category,
  };
}

